import type { Plan, ToolCallBlock } from "@corpix/shared";
import { estimateTokens } from "@corpix/shared";
import type { CompletionRequest, CompletionResponse, LLMProvider } from "./types";

export interface MockProviderOptions {
  /** Plan returned when the caller forces `submit_plan`. */
  plan?: Plan;
  /** Override the response for any request; return undefined to use the default. */
  respond?: (
    request: CompletionRequest,
    turn: number,
  ) => CompletionResponse | undefined;
  /** File the scripted worker writes before reporting. */
  workerFile?: string;
}

/**
 * Deterministic provider used for demo mode and integration tests. It never
 * touches the network and never costs money.
 */
export class MockProvider implements LLMProvider {
  readonly name = "mock";
  private readonly turns = new Map<string, number>();
  private readonly plan?: Plan;
  private readonly workerFile?: string;
  private readonly respondOverride?: MockProviderOptions["respond"];

  constructor(options: MockProviderOptions = {}) {
    this.plan = options.plan;
    this.workerFile = options.workerFile;
    this.respondOverride = options.respond;
  }

  async complete(request: CompletionRequest): Promise<CompletionResponse> {
    const key = request.system.slice(0, 64) + request.messages.length;
    const turn = (this.turns.get(key) ?? 0) + 1;
    this.turns.set(key, turn);

    const override = this.respondOverride?.(request, turn);
    if (override) return override;

    const usage = {
      inputTokens: estimateTokens(request.system) + request.messages.length * 40,
      outputTokens: 32,
    };

    // The office mind asks for JSON in a single user turn. Answer it with a
    // deterministic but varied character so demo mode still feels alive.
    const mindPrompt = request.messages
      .flatMap((message) => message.content)
      .filter((block) => block.type === "text")
      .map((block) => block.text)
      .find((text) => text.startsWith("[corpix-mind]"));
    if (mindPrompt) {
      const mind = mockMind(mindPrompt, turn);
      return {
        content: [{ type: "text", text: JSON.stringify(mind) }],
        stopReason: "end_turn",
        usage: { ...usage, outputTokens: estimateTokens(JSON.stringify(mind)) },
      };
    }

    const boss = request.tools.some((tool) => tool.name === "submit_plan");
    if (request.toolChoice?.name === "submit_plan" || boss) {
      const plan = this.plan ?? planFromRoles(rolesFromTools(request));
      return {
        content: [toolCall("call_plan", "submit_plan", plan)],
        stopReason: "tool_use",
        usage,
      };
    }

    if (request.toolChoice?.name === "submit_report") {
      return {
        content: [toolCall("call_report", "submit_report", reportPayload("done", "Scripted report"))],
        stopReason: "tool_use",
        usage,
      };
    }

    const alreadyWorked = request.messages.some(
      (message) =>
        message.role === "user" &&
        message.content.some((block) => block.type === "tool_result"),
    );

    if (!alreadyWorked) {
      const target = this.workerFile ?? targetFileFromPrompt(request.system);
      return {
        content: [
          {
            type: "text",
            text: `Reading the shared context, then creating ${target}.`,
          },
          toolCall("call_write", "write_file", {
            path: target,
            content: `// generated by the mock provider\nexport const ok = true;\n`,
          }),
        ],
        stopReason: "tool_use",
        usage,
      };
    }

    const files = request.messages
      .flatMap((message) => message.content)
      .filter((block) => block.type === "tool_result")
      .map((block) => block.content)
      .join("\n");
    const written = [...files.matchAll(/Wrote (\S+)/g)].map((match) => match[1] as string);

    return {
      content: [
        toolCall(
          "call_report",
          "submit_report",
          reportPayload("done", "Mock worker finished its task.", written),
        ),
      ],
      stopReason: "tool_use",
      usage,
    };
  }
}

function toolCall(id: string, name: string, input: unknown): ToolCallBlock {
  return { type: "tool_call", id, name, input };
}

function reportPayload(status: "done" | "blocked" | "failed", summary: string, files: string[] = []) {
  return {
    status,
    summary,
    filesChanged: files,
    commandsRun: [],
    openIssues: [],
  };
}

/** Turn the first write glob in the prompt into a concrete file path. */
function targetFileFromPrompt(system: string): string {
  const match = system.match(/write files inside your scope:\s*([^\n]+)/i);
  const globs = match?.[1]?.split(",").map((glob) => glob.trim()) ?? [];
  const glob = globs.find((candidate) => candidate.length > 0) ?? "**";
  if (!glob.includes("*")) return glob.replace(/\.$/, "");
  const base = glob.replace(/\*+.*$/, "").replace(/\/$/, "");
  const name = "mock-output.ts";
  return base.length > 0 ? `${base}/${name}` : name;
}

function rolesFromTools(request: CompletionRequest): string[] {
  for (const tool of request.tools) {
    const properties = tool.jsonSchema.properties as
      | Record<string, unknown>
      | undefined;
    const tasks = properties?.tasks as
      | { items?: { properties?: { role?: { enum?: unknown } } } }
      | undefined;
    const values = tasks?.items?.properties?.role?.enum;
    if (Array.isArray(values)) return values.filter((v): v is string => typeof v === "string");
  }
  return ["backend", "frontend"];
}

/** Scripted plan that exercises the scheduler and a dependency edge. */
export function planFromRoles(roles: readonly string[]): Plan {
  const has = (role: string): boolean => roles.includes(role);
  const workers = ["backend", "frontend", "devops", "qa"].filter(has);
  const chosen = workers.length > 0 ? workers.slice(0, 3) : [roles[0] ?? "backend"];
  const tasks: Plan["tasks"] = chosen.map((role, index) => ({
    id: `t${index + 1}`,
    role,
    title: scriptedTitle(role),
    instructions: scriptedInstructions(role),
    dependsOn: [],
    acceptanceCriteria: [`The ${role} deliverable exists and is readable`],
  }));
  if (tasks.length >= 2) {
    const last = tasks[tasks.length - 1] as Plan["tasks"][number];
    last.dependsOn = tasks.slice(0, -1).map((task) => task.id);
  }
  return {
    summary: `Scripted plan for: ${chosen.join(", ")}`,
    tasks,
  };
}

function scriptedTitle(role: string): string {
  switch (role) {
    case "backend":
      return "Create the API entry point";
    case "frontend":
      return "Create the web entry point";
    case "devops":
      return "Add a container definition";
    case "qa":
      return "Add a smoke test";
    default:
      return `Do the ${role} work`;
  }
}

function scriptedInstructions(role: string): string {
  return `Create one small ${role} deliverable that satisfies the acceptance criteria.`;
}

export function defaultPlan(): Plan {
  return planFromRoles(["backend", "frontend", "qa"]);
}


/**
 * Demo-mode mind. It reads the prompt enough to know who it is and whether it is
 * deciding or replying, then produces a varied in-character answer. Real
 * deployments use the configured model; this only exists so `provider: mock` is
 * not a dead office.
 */
function mockMind(prompt: string, turn: number): Record<string, unknown> {
  const name = /You are ([^,\n]+),/.exec(prompt)?.[1] ?? "someone";
  const role = detectRole(prompt);
  const seed = hash(`${name}:${role}:${turn}`);
  const replying = prompt.includes("They just spoke to you.") || prompt.includes("You started this conversation.");
  const transcript = [...prompt.matchAll(/^(?:you|([A-Z][\w .-]+)): (.+)$/gm)];
  const last = transcript.at(-1);
  const lastText = last?.[2] ?? "";

  if (replying) {
    const reactions = [
      `Fair. But ${pick(["the edge cases", "the retry path", "that assumption"], seed)} still worry me.`,
      `Hm. I see it differently, but go on.`,
      `That is actually a good point. I'll take another look.`,
      `I'm not in the mood to argue about ${pick(["naming", "spacing", "YAML"], seed)} right now.`,
      `You're describing the happy path. What happens when it fails?`,
      `Okay, that made me laugh. Fine, you win this one.`,
      `I'm tired. Can we do this after coffee?`,
    ];
    return {
      thought: `They said: ${lastText.slice(0, 80)}`,
      say: reactions[seed % reactions.length],
      mood: {
        valence: ((seed % 7) - 3) / 6,
        arousal: ((seed % 5) - 2) / 4,
        label: pick(["interested", "annoyed", "amused", "tired", "stubborn"], seed),
      },
      opinion: { sentiment: ((seed % 5) - 2) / 8, note: pick(["worth listening to", "gets defensive", "sharp", "distracted lately"], seed) },
    };
  }

  const actions = ["work", "coffee", "water", "smoke", "whiteboard", "window", "wander", "talk", "stretch", "meeting"];
  const action = actions[seed % actions.length];
  const place =
    action === "coffee" ? "coffee"
    : action === "water" ? "water"
    : action === "smoke" ? "smoke"
    : action === "whiteboard" ? "whiteboard"
    : action === "window" ? "window"
    : action === "meeting" ? "meeting"
    : action === "wander" ? "wander"
    : "desk";
  const colleague = /- ([\w .-]+) \([\w-]+, id ([\w-]+)\)/.exec(prompt);
  const sayPool = [
    "",
    "I need caffeine before I look at that again.",
    "Who touched the deploy script?",
    "This is going to bite us later.",
    "Finally, something that works.",
    "I have been staring at the same line for ten minutes.",
  ];
  return {
    thought: pick([
      "I should check the diff before anyone else does.",
      "Nobody is going to notice this if I do it quietly.",
      "I am not paid enough to debug YAML today.",
      "Actually, a short break would help.",
    ], seed),
    action,
    place,
    target: action === "talk" && colleague ? colleague[2] : undefined,
    label:
      action === "coffee" ? "getting coffee"
      : action === "smoke" ? "on a smoke break"
      : action === "whiteboard" ? "at the whiteboard"
      : action === "window" ? "staring out the window"
      : action === "wander" ? "walking it off"
      : action === "talk" ? "looking for someone"
      : "at the desk",
    say: sayPool[seed % sayPool.length],
    seconds: 8 + (seed % 12),
    mood: {
      valence: ((seed % 9) - 4) / 8,
      arousal: ((seed % 5) - 2) / 4,
      label: pick(["focused", "restless", "grumpy", "content", "curious", "wiped out"], seed),
    },
    remember: pick([
      "The build was green, for once.",
      "Someone moved my chair.",
      "I still owe a review.",
    ], seed),
  };
}

function detectRole(prompt: string): string {
  for (const role of ["boss", "frontend", "backend", "devops", "qa", "docs"]) {
    if (prompt.toLowerCase().includes(`(${role},`) || prompt.toLowerCase().includes(` ${role} `)) return role;
  }
  return "backend";
}

function pick<T>(items: readonly T[], seed: number): T {
  return items[seed % items.length] as T;
}

function hash(value: string): number {
  let h = 2166136261;
  for (let i = 0; i < value.length; i++) {
    h ^= value.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}
